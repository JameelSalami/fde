"""LangGraph pipeline for the engineer's Excel-first reporting workflow.

FDE Haskell calculates. Python packages. Azure OpenAI optionally suggests
investigation questions, but no model or graph node changes source systems.
Excel desktop/Office Scripts remain user-operated publication surfaces.
"""
from __future__ import annotations
import csv
from datetime import datetime,timezone
from hashlib import sha256
import json
import os
from pathlib import Path
import re
from typing import Any,TypedDict
from langgraph.graph import StateGraph,START,END

from kpi import Refused,intake,assess,baseline_questions
from azure_model import AzureRefused,call_azure,offline_draft

ROOT=Path(__file__).resolve().parents[2]
OUTPUTS=ROOT/".local"/"operations-excel"/"outputs"
RUNID=re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}\Z")

class State(TypedDict,total=False):
    summary_csv:str
    losses_csv:str
    run_id:str
    source_class:str
    mode:str
    run_dir:str
    raw:dict[str,Any]
    report:dict[str,Any]
    draft:dict[str,Any]
    model_status:str
    error:str
    status:str
    outputs:dict[str,str]

def _prepare(state:State)->State:
    try:
        runid=state["run_id"]
        if not RUNID.fullmatch(runid):
            raise Refused("run-identifier-refused")
        OUTPUTS.mkdir(parents=True,mode=0o700,exist_ok=True)
        st=OUTPUTS.lstat()
        if OUTPUTS.is_symlink() or not OUTPUTS.is_dir() or st.st_mode & 0o077:
            raise Refused("private-output-custody-refused")
        dest=OUTPUTS/runid
        if dest.exists() or dest.is_symlink():
            raise Refused("run-already-exists")
        dest.mkdir(mode=0o700)
        raw=intake(state["summary_csv"],state["losses_csv"],state["source_class"])
        return {"run_dir":str(dest),"raw":raw,"status":"input-validated"}
    except (Refused,KeyError,OSError,ValueError):
        return {"status":"refused","error":"report-input-refused"}

def _kpi(state:State)->State:
    try:
        result=assess(state["raw"])
        return {"report":result,"status":"fde-haskell-kpis-calculated"}
    except (Refused,KeyError,OSError,ValueError):
        return {"status":"refused","error":"fde-kpi-assessment-refused"}

def _investigate(state:State)->State:
    report=state["report"]
    if state.get("mode")=="offline":
        return {"draft":offline_draft(report),"model_status":"not-requested","status":"investigation-prepared"}
    if state.get("mode")!="azure":
        return {"status":"refused","error":"unknown-model-mode"}
    try:
        draft=call_azure(report)
        return {"draft":draft,"model_status":"azure-generated","status":"investigation-prepared"}
    except (AzureRefused,RuntimeError,ValueError,TimeoutError,OSError,Exception) as err:
        # A model failure does not erase a verified deterministic KPI result;
        # visible fallback is not presented as generated by Azure.
        return {"draft":offline_draft(report),"model_status":"azure-unavailable-or-refused",
                "status":"investigation-prepared"}

def _write_csv(path:Path,header:list[str],rows:list[list[str]])->None:
    with path.open("x",encoding="utf-8",newline="") as out:
        os.fchmod(out.fileno(),0o600)
        writer=csv.writer(out)
        writer.writerow(header)
        for row in rows:writer.writerow(row)

def _write_json(path:Path,body:dict[str,Any])->None:
    with path.open("x",encoding="utf-8") as out:
        os.fchmod(out.fileno(),0o600)
        json.dump(body,out,sort_keys=True,indent=2,ensure_ascii=False)
        out.write("\n")

def _deliver(state:State)->State:
    try:
        dest=Path(state["run_dir"])
        report=state["report"]
        draft=state["draft"]
        performance=dest/"performance.json"
        investigation=dest/"investigation.json"
        _write_json(performance,report)
        _write_json(investigation,draft)
        summary=[
           [r["periodId"],r["lineId"],r["plannedUnits"],r["goodUnits"],
            r["shortfallUnits"],r["attainmentPercent"] or "",r["lossStatus"],
            r["unclassifiedUnits"]] for r in report["periods"]]
        _write_csv(dest/"performance.csv",["Period","Line","Planned","Good",
             "Shortfall","AttainmentPercent","LossStatus","Unclassified"],summary)
        lossrows=[
          [r["periodId"],r["lineId"],p["id"],p["units"],
           p["sharePercent"] or "",p["cumulativePercent"] or ""]
          for r in report["periods"] for p in r["pareto"]]
        _write_csv(dest/"loss_pareto.csv",["Period","Line","LossCategory",
            "Units","SharePercent","CumulativePercent"],lossrows)
        questions=baseline_questions(report)
        _write_csv(dest/"investigation.csv",["Question","Reviewer","Status"],
                   [[q,"","To review"] for q in questions])
        manifest={
            "schema":"fde.excel-automation-handoff/v1","status":"excel-render-ready",
            "authority":"human-engineering-workflow","caseSource":"manual-export-or-synthetic",
            "runId":state["run_id"],"modelStatus":state["model_status"],
            "sourceDigests":report["sourceDigests"],"kernelSha256":report["kernelSha256"],
            "reviewRequired":True,"cloudResourcesCreated":False,
            "vendorReadPerformed":False,"vendorWritePerformed":False,
            "generatedAt":datetime.now(timezone.utc).isoformat(),
            "sha256":{x.name:sha256(x.read_bytes()).hexdigest()
                       for x in dest.iterdir() if x.is_file()},
            "plannedExcelSurface":"Windows desktop Excel; no online auth assumed",
            "limitations":report["scope"]}
        _write_json(dest/"manifest.json",manifest)
        return {"status":"excel-render-ready",
                "outputs":{x.name:str(x) for x in dest.iterdir() if x.is_file()}}
    except (Refused,KeyError,OSError,ValueError):
        return {"status":"refused","error":"report-artifact-preparation-refused"}

def _refuse(state:State)->State:
    return {"status":"refused"}

def _route(state:State)->str:
    return "refuse" if state.get("error") else "proceed"

def graph():
    g=StateGraph(State)
    g.add_node("validate_manual_exports",_prepare)
    g.add_node("calculate_with_fde_haskell",_kpi)
    g.add_node("azure_or_offline_investigation",_investigate)
    g.add_node("prepare_excel_handoff",_deliver)
    g.add_node("refuse",_refuse)
    g.add_edge(START,"validate_manual_exports")
    g.add_conditional_edges("validate_manual_exports",_route,
         {"refuse":"refuse","proceed":"calculate_with_fde_haskell"})
    g.add_conditional_edges("calculate_with_fde_haskell",_route,
         {"refuse":"refuse","proceed":"azure_or_offline_investigation"})
    g.add_conditional_edges("azure_or_offline_investigation",_route,
         {"refuse":"refuse","proceed":"prepare_excel_handoff"})
    g.add_edge("prepare_excel_handoff",END)
    g.add_edge("refuse",END)
    return g.compile()

def run(summary_csv:str,losses_csv:str,run_id:str,
        source_class:str="manual-export",mode:str="offline")->State:
    value=graph().invoke({"summary_csv":summary_csv,"losses_csv":losses_csv,
            "run_id":run_id,"source_class":source_class,"mode":mode})
    return {x:value[x] for x in ("status","error","model_status","outputs") if x in value}
