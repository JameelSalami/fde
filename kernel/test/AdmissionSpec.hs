{-# LANGUAGE OverloadedStrings #-}
module Main (main) where
import Control.Monad (unless,when)
import Data.Aeson (Value(..),object,(.=))
import qualified Data.Aeson.Key as Key
import qualified Data.Aeson.KeyMap as KM
import Data.Text (Text)
import qualified Data.Text as T
import System.Environment (getArgs)
import System.Exit (exitFailure)
import FDE.Kernel
import FDE.Admission
import FDE.AdmissionWire

-- Independent W1 examples: native reported evidence, never physical output.
sourceA,sourceB :: Source
sourceA = Source "erp" "erpnext" "plant-r" "WO-57" "WO-57" "v8" "In Process"
  "19.000000000" "2.125" "Nos" "handwritten-fixture" "2026-10-29T01:00:00Z" (T.replicate 64 "a")
sourceB = Source "mes" "openmes" "site-s" "731" "B-57" "r9" "DONE"
  "19" "7.375" "pcs" "handwritten-fixture" "2026-10-29T01:00:02Z" (T.replicate 64 "b")

sources :: CompileInput
sources = CompileInput sourceA sourceB (Binding "plant-r" "WO-57" "site-s" "731"
  "synthetic-native-import-reviewed" "synthetic-pcs-equals-Nos")

ctx :: Context
ctx = Context "case-57" "set-57" "admission-57" "assessment-57" "evaluation-57"
  "fde.w1.lab-review/v1" "fde.w1.synthetic-pcs-Nos/v1" "fde.semantic-w1/v1"

receiptA,receiptB :: Receipt
receiptA = Receipt "receipt-erp-57" "erp" "plant-r" "WO-57" "v8"
  "2026-10-29T01:00:00Z" (T.replicate 64 "a") "fixture"
receiptB = Receipt "receipt-mes-57" "mes" "site-s" "731" "r9"
  "2026-10-29T01:00:02Z" (T.replicate 64 "b") "fixture"

-- Hand authored, not generated by expectedMembers or copied from outputs.
completeMembers :: [Member]
completeMembers =
  [Member "set-57/erp.plan" "erp" "plan" "receipt-erp-57" "WO-57" "v8" "19.000000000" "Nos"
  ,Member "set-57/mes.plan" "mes" "plan" "receipt-mes-57" "731" "r9" "19" "pcs"
  ,Member "set-57/erp.report" "erp" "report" "receipt-erp-57" "WO-57" "v8" "2.125" "Nos"
  ,Member "set-57/mes.report" "mes" "report" "receipt-mes-57" "731" "r9" "7.375" "pcs"]

fixture :: Admission
fixture = Admission ctx sources [receiptA,receiptB] completeMembers

live :: Admission
live = fixture {pinnedInput=sources {erp=sourceA {sourceClass="isolated-synthetic-native"}
                                  ,mes=sourceB {sourceClass="isolated-synthetic-native"}}
               ,receipts=[receiptA {authentication="tls13-read-only"},receiptB {authentication="tls13-read-only"}]}

isRight :: Either a b -> Bool
isRight (Right _) = True
isRight _ = False

rejected :: Either a b -> Bool
rejected = not . isRight

check :: [String] -> String -> Bool -> IO ()
check chosen name passed = when (null chosen || takeWhile (/= ' ') name `elem` chosen) $ do
  putStrLn ((if passed then "PASS " else "FAIL ") <> name)
  unless passed exitFailure

field :: Text -> Value -> Maybe Value
field k (Object o) = KM.lookup (Key.fromText k) o
field _ _ = Nothing

main :: IO ()
main = do
  chosen <- getArgs
  let good = admit fixture
      passing = isRight good
      first = head completeMembers
      rest = tail completeMembers
      changed a = fixture {context=a}
  check chosen "KA01 exact complete candidate membership" $
    passing && admit fixture {members=reverse completeMembers} == good &&
    rejected (admit fixture {members=tail completeMembers}) &&
    rejected (admit fixture {members=completeMembers ++ [first]}) &&
    rejected (admit fixture {members=first:first:drop 2 completeMembers})
  check chosen "KA02 candidate content remains source bound" $
    passing &&
    admit fixture {members=first {memberQuantity="20"}:rest} == Left "candidate-content-mismatch" &&
    rejected (admit fixture {members=first {memberReceiptId="receipt-mes-57"}:rest}) &&
    rejected (admit fixture {members=first {memberRevision="v9"}:rest})
  check chosen "KA03 source receipt binds exact capture and revision" $
    passing &&
    admit fixture {receipts=[receiptA {sourceRevision="v7"},receiptB]} == Left "source-receipt-mismatch" &&
    rejected (admit fixture {receipts=[receiptA {querySha256=T.replicate 64 "0"},receiptB]}) &&
    rejected (admit fixture {receipts=[receiptA {receiptObservedAt="2026-10-29T02:00:00Z"},receiptB]})
  check chosen "KA04 host authentication is required for the declared grade" $
    isRight (admit live) && passing &&
    admit live {receipts=[receiptA,receiptB]} == Left "unverified-source-authentication" &&
    admit fixture {receipts=[receiptA {authentication="tls13-read-only"},receiptB]} == Left "unverified-source-authentication"
  check chosen "KA05 policy and mapping pins cannot float" $
    passing &&
    admit (changed ctx {policyId="fde.w1.production/v1"}) == Left "unsupported-admission-policy" &&
    admit (changed ctx {mappingId="names-look-similar"}) == Left "unsupported-mapping-policy"
  check chosen "KA06 incompatible kernel dependency refuses" $
    passing &&
    admit (changed ctx {kernelContract="fde.semantic-w1/v2"}) == Left "incompatible-kernel-contract"
  check chosen "KA07 admission identity domains and receipt membership remain distinct" $
    passing &&
    admit (changed ctx {admissionId="case-57"}) == Left "invalid-admission-identities" &&
    rejected (admit fixture {receipts=[receiptA,receiptA]}) &&
    rejected (admit fixture {receipts=[receiptA]}) &&
    rejected (admit fixture {receipts=[receiptA {receiptId="case-57"},receiptB]})
  check chosen "KA08 grade cannot promote fixtures or mix evidence" $
    case (good,admit live) of
      (Right f,Right l) -> evidenceGrade f == "fixture-demonstration" &&
        evidenceGrade l == "authenticated-lab-review" &&
        admit live {pinnedInput=sources {erp=sourceA {sourceClass="isolated-synthetic-native"}},receipts=[receiptA {authentication="tls13-read-only"},receiptB]} == Left "mixed-evidence-grades"
      _ -> False
  check chosen "KA09 pinned replay compares all evaluation dependencies and decisions" $
    case good of
      Left _ -> False
      Right s -> replay fixture s == Right s &&
        replay fixture s {decision=(decision s) {classification="aligned-reports"}} == Left "pinned-replay-mismatch" &&
        replay (changed ctx {evaluationId="evaluation-new"}) s == Left "pinned-replay-mismatch"
  check chosen "KA10 admitted review remains non-authoritative and exact" $
    case good of
      Left _ -> False
      Right s ->
        reportedDelta (decision s) == "5.25" &&
        field "businessTruthSelected" (renderSnapshot s) == Just (Bool False) &&
        field "postingPermitted" (renderSnapshot s) == Just (Bool False) &&
        field "physicalProductionCertified" (renderSnapshot s) == Just (Bool False) &&
        rejected (admit fixture {pinnedInput=sources {binding=(binding sources) {mesNativeId="732"}}})
  check chosen "KA11 wire schema refuses caller authority and unrecognized fields" $
    isRight (processAdmission (renderAdmission fixture)) &&
    case renderAdmission fixture of
      Object o -> rejected (processAdmission (Object (KM.insert "trusted" (Bool True) o)))
      _ -> False
  check chosen "KA12 replay refuses altered snapshot and fresh input fields" $
    case good of
      Left _ -> False
      Right s ->
        let req expected = object ["schema" .= ("fde.w1-replay-request/v1" :: Text)
                                  ,"admission" .= renderAdmission fixture,"expected" .= expected]
            valid = req (renderSnapshot s)
        in isRight (processAdmission valid) &&
          (case renderSnapshot s of
            Object o -> rejected (processAdmission (req (Object (KM.insert "physicalProductionCertified" (Bool True) o))))
            _ -> False) &&
          (case valid of
            Object o -> rejected (processAdmission (Object (KM.insert "freshSources" (Bool True) o)))
            _ -> False)
  putStrLn "FDE W1 admission: all independent law tests passed."
